BEGIN;
CREATE TABLE IF NOT EXISTS study_room (
    id uuid PRIMARY KEY,
    owner_id bigint NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    name varchar(80) NOT NULL,
    phase varchar(12) NOT NULL DEFAULT 'WAITING' CHECK (phase IN ('WAITING', 'FOCUS', 'BREAK')),
    deadline timestamptz,
    remaining_ms bigint NOT NULL DEFAULT 0,
    revision bigint NOT NULL DEFAULT 0,
    expires_at timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_study_room_owner ON study_room(owner_id);
CREATE TABLE IF NOT EXISTS study_room_member (
    room_id uuid NOT NULL REFERENCES study_room(id) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    joined_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (room_id, user_id)
);
CREATE TABLE IF NOT EXISTS study_room_message (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id uuid NOT NULL REFERENCES study_room(id) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    client_id uuid NOT NULL,
    body varchar(1000) NOT NULL,
    image_type varchar(20),
    image_bytes bytea,
    sent_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (room_id, user_id, client_id)
);
CREATE INDEX IF NOT EXISTS idx_study_room_message_room ON study_room_message(room_id, id DESC);
COMMIT;
